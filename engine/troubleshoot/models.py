"""Data models for the Troubleshoot module.

Provides structures for diagnostic steps, findings, RCA reports, and confidence levels.
"""

from enum import Enum
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field
import datetime


class ConfidenceLevel(str, Enum):
    CONFIRMED = "CONFIRMED"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class FindingStatus(str, Enum):
    CONFIRMED = "CONFIRMED"
    HYPOTHESIS = "HYPOTHESIS"
    CONTRADICTION = "CONTRADICTION"
    INSUFFICIENT_EVIDENCE = "INSUFFICIENT_EVIDENCE"


class DiagnosticStep(BaseModel):
    """One atomic diagnostic action performed on a device."""
    device_id: str = Field(..., description="Unique identifier of the target device (inventory ID)")
    connector: str = Field(..., description="Connector type used (ssh, api, snmp, winbox)")
    command: str = Field(..., description="Command or API call that was executed")
    raw_output: str = Field(..., description="Raw text/JSON output returned by the device (redacted if needed)")
    raw_output_hash: str = Field("", description="SHA-256 hash of the original raw output (before any truncation)")
    raw_output_ref: str = Field("", description="Filesystem path to the stored raw output file (protected)")
    is_truncated: bool = Field(False, description="True if the stored raw output was truncated for size limits")
    parsed_result: Dict[str, Any] = Field(default_factory=dict, description="Structured result after parsing")
    timestamp: str = Field(..., description="ISO-8601 timestamp when the step was run")


class Finding(BaseModel):
    """A single observation derived from diagnostic steps."""
    finding_id: str = Field(
        default_factory=lambda: datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d%H%M%S%f"),
        description="Unique identifier for the finding"
    )
    description: str = Field(..., description="Human-readable description of the finding")
    device_id: str = Field("unknown", description="Device the finding pertains to")
    evidence_steps: List[str] = Field(default_factory=list, description="List of DiagnosticStep identifiers supporting this finding")
    evidence_timestamps: List[str] = Field(default_factory=list, description="Timestamps of the supporting evidence")
    evidence_freshness: str = Field("UNKNOWN", description="Whether evidence is FRESH, STALE, or UNKNOWN based on policy")
    topology_relation: Optional[str] = Field(None, description="Relation to other devices from topology (e.g., upstream/downstream)")
    status: FindingStatus = Field(FindingStatus.HYPOTHESIS, description="Finding status")
    confidence: ConfidenceLevel = Field(ConfidenceLevel.LOW, description="Confidence level for this finding")
    recommended_action: Optional[str] = Field(None, description="Suggested remediation for confirmed findings")
    alternative_causes: List[str] = Field(default_factory=list, description="Possible other explanations")
    explanation: Optional[str] = Field(None, description="Explanation of why this status/confidence was assigned")


class RCAReport(BaseModel):
    """Root-cause analysis report generated by the troubleshooting engine."""
    incident_id: str = Field(..., description="Unique incident identifier")
    summary: str = Field(..., description="One-sentence summary of the problem")
    symptoms: List[str] = Field(default_factory=list, description="User-reported symptoms")
    target_devices: List[str] = Field(default_factory=list, description="Device IDs involved in the investigation")
    topology_snapshot: Dict[str, Any] = Field(default_factory=dict, description="Relevant topology sub-graph at investigation time")
    steps: List[DiagnosticStep] = Field(default_factory=list, description="Ordered list of diagnostic actions performed")
    findings: List[Finding] = Field(default_factory=list, description="Key observations derived from the steps")
    probable_root_cause: Optional[str] = Field(None, description="Most likely root cause description (only if CONFIRMED)")
    confidence: ConfidenceLevel = Field(ConfidenceLevel.LOW, description="Overall confidence level of the root cause")
    recommendations: List[str] = Field(default_factory=list, description="Suggested remediation actions for the incident")
    generated_at: str = Field(..., description="ISO-8601 timestamp when the report was generated")
